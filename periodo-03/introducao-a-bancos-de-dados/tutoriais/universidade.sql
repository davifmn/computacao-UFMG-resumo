-- Banco de dados de exemplo: uma universidade fictícia.
-- Os nomes são inventados. Use em https://sqliteonline.com, no sqlite3 ou no tutorial do Resumão.

CREATE TABLE professores (
    id           TEXT PRIMARY KEY,
    nome         TEXT NOT NULL,
    departamento TEXT NOT NULL
);

CREATE TABLE alunos (
    matricula     INTEGER PRIMARY KEY,
    nome          TEXT NOT NULL,
    curso         TEXT NOT NULL CHECK (curso IN ('CC', 'SI', 'MC')),
    ano_ingresso  INTEGER NOT NULL
);

CREATE TABLE disciplinas (
    codigo        TEXT PRIMARY KEY,
    nome          TEXT NOT NULL,
    creditos      INTEGER NOT NULL,
    periodo       INTEGER NOT NULL,
    professor_id  TEXT REFERENCES professores(id)      -- pode ser NULL: sem professor definido
);

CREATE TABLE matriculas (
    matricula  INTEGER REFERENCES alunos(matricula),
    codigo     TEXT REFERENCES disciplinas(codigo),
    semestre   TEXT NOT NULL,                          -- ex.: '2024/1'
    nota       REAL CHECK (nota BETWEEN 0 AND 100),    -- NULL: ainda cursando
    PRIMARY KEY (matricula, codigo, semestre)
);

